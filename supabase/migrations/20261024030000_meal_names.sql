-- Master meal list for the manual diet planner's meal picker. Seeded with the
-- clinic's meal names (meal names.xlsx); meals typed by hand in the planner are
-- added when the plan is saved (source = 'planner'). Names are unique ignoring
-- case, spaces and punctuation.
create table if not exists public.meal_names (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 200),
  name_normalized text generated always as (regexp_replace(lower(name), '[^a-z0-9]+', '', 'g')) stored,
  source text not null default 'planner' check (source in ('clinic_list', 'planner')),
  created_at timestamptz not null default now(),
  constraint meal_names_name_normalized_key unique (name_normalized)
);

alter table public.meal_names enable row level security;

drop policy if exists "staff all meal_names" on public.meal_names;
create policy "staff all meal_names" on public.meal_names
  for all to authenticated
  using (public.portal_client_id() is null)
  with check (public.portal_client_id() is null);

